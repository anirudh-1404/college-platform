async function seedColleges() {
  try {
    console.log("Connecting to MongoDB...");
    await mongoose.connect(process.env.MONGO_URI);
    console.log("Connected to MongoDB successfully.");

    let insertedCount = 0;
    let updatedCount = 0;

    for (const collegeData of collegesToSeed) {
      const existing = await College.findOne({ slug: collegeData.slug });
      if (existing) {
        await College.updateOne({ slug: collegeData.slug }, { $set: collegeData });
        console.log(`Updated existing college: ${collegeData.name} (${collegeData.slug})`);
        updatedCount++;
      } else {
        await College.create(collegeData);
        console.log(`Inserted new college: ${collegeData.name} (${collegeData.slug})`);
        insertedCount++;
      }
    }

    const totalColleges = await College.countDocuments({ profileStatus: "published" });
    console.log(`\n========================================`);
    console.log(`Seeding Complete!`);
    console.log(`Newly Inserted: ${insertedCount}`);
    console.log(`Updated: ${updatedCount}`);
    console.log(`Total Live Published Colleges in DB: ${totalColleges}`);
    console.log(`========================================\n`);

    process.exit(0);
  } catch (err) {
    console.error("Failed to seed colleges:", err);
    process.exit(1);
  }
}

seedColleges();
